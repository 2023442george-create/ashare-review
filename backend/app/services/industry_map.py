_INDEX: dict[str, str] = {alias: sw for sw, aliases in SW_LEVEL1.items() for alias in aliases}


def to_sw(name: str | None) -> str | None:
    """把东财细分行业名归并到申万一级。

    东财会把长行业名截断成 4 个汉字（汽车零部、自动化设、炼化及贸、房地产开），
    所以除精确匹配外，对 4 字名再做一次前缀匹配；但只在**唯一命中**时才采纳，
    避免「电力」被误并到「电力设备」这类事故。
    """
    n = (name or "").strip()
    if not n:
        return None
    if n in _INDEX:
        return _INDEX[n]
    if len(n) == 4:
        hits = {sw for alias, sw in _INDEX.items() if alias.startswith(n)}
        if len(hits) == 1:
            return hits.pop()
    return None
