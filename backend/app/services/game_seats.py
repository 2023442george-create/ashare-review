def match(dept_name: str) -> dict | None:
    if not dept_name:
        return None
    for s in SEATS:
        for kw in s["kw"]:
            if kw in dept_name:
                return {"seat": s["name"], "tag": s["tag"], "style": s["style"], "next": s["next"],
                        "matched_kw": kw}
    return None


def is_noise(dept_name: str) -> bool:
    """量化通道/对倒席位：方向意义弱"""
    m = match(dept_name)
    return bool(m and m["tag"] in ("量化通道", "量化/机构通道"))